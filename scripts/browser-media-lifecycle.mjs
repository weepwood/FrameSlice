import {chromium} from 'playwright-core';
import {readFile,mkdir} from 'node:fs/promises';
import {selectOption,themeOption} from './select-option.mjs';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true,args:['--no-sandbox']});
const url=process.env.APP_URL??'http://127.0.0.1:4173/FrameSlice/';
const fixture=async name=>Buffer.from((await readFile(new URL('../tests/fixtures/'+name,import.meta.url),'utf8')).trim(),'base64');
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
 await page.addInitScript(()=>{
   Object.defineProperty(window,'showDirectoryPicker',{configurable:true,value:async()=>navigator.storage.getDirectory()});
   const create=URL.createObjectURL.bind(URL),revoke=URL.revokeObjectURL.bind(URL);
   window.__race={held:[],previews:0,revoked:[],release(){for(const run of this.held.splice(0))run()}};
   URL.createObjectURL=blob=>create(blob);
   URL.revokeObjectURL=url=>{window.__race.revoked.push(url);return revoke(url)};
   const states=new WeakMap(),original=Worker.prototype.postMessage;
   Worker.prototype.postMessage=function(msg,...args){if(msg?.kind==='start'&&msg.mode==='frames'&&!msg.folder&&msg.width===1280&&msg.file.name==='old-race.mp4')states.set(this,{seen:false});return original.call(this,msg,...args)};
   const desc=Object.getOwnPropertyDescriptor(Worker.prototype,'onmessage');
   Object.defineProperty(Worker.prototype,'onmessage',{...desc,set(fn){desc.set.call(this,typeof fn!=='function'?fn:function(event){
     const state=states.get(this);if(!state)return fn.call(this,event);
     if(event.data?.kind==='preview'&&!state.seen){state.seen=true;window.__race.previews++;return fn.call(this,event)}
     if(state.seen){window.__race.held.push(()=>fn.call(this,event));return}
     return fn.call(this,event);
   })}});
 });
 await page.goto(url,{waitUntil:'networkidle'});
 const input=page.locator('input[type=file]');
 const bytes=await fixture('black-h264-aac.mp4.b64');
 await input.setInputFiles({name:'old-race.mp4',mimeType:'video/mp4',buffer:bytes});
 await page.locator('.file-codec').waitFor();
 const timeline=page.getByRole('region',{name:'媒体时间轴'});
 await timeline.getByRole('button',{name:'生成缩略图'}).click();
 const oldThumb=timeline.locator('.fs-timeline-thumbs img').first();
 await oldThumb.waitFor();
 const oldUrl=await oldThumb.getAttribute('src');
 await page.waitForFunction(()=>window.__race.held.length>0);
 await input.setInputFiles({name:'new-race.mp4',mimeType:'video/mp4',buffer:bytes});
 await page.waitForFunction(old=>window.__race.revoked.includes(old),oldUrl);
 await page.evaluate(()=>window.__race.release());
 await page.locator('.file-codec').waitFor();
 if(await timeline.locator('.fs-timeline-thumbs img').count()!==0)throw Error('stale previews appeared in new source');
 await timeline.getByRole('button',{name:'生成缩略图'}).click();
 await timeline.locator('.fs-timeline-thumbs img').first().waitFor();
 await timeline.getByRole('button',{name:'生成缩略图'}).waitFor();
 const current=await timeline.locator('.fs-timeline-thumbs img').evaluateAll(xs=>xs.map(x=>x.src));
 if(current.includes(oldUrl)||await page.evaluate(urls=>urls.some(u=>window.__race.revoked.includes(u)),current))throw Error('new preview resource incorrectly released');
 await input.setInputFiles({name:'many.mp4',mimeType:'video/mp4',buffer:await fixture('many-keyframes-h264.mp4.b64')});
 await page.locator('.file-codec').waitFor();
 await selectOption(page,'分割方式','按视频时长');
 await page.getByRole('spinbutton',{name:'每段时长（分钟）'}).fill('0.018');
 await page.getByRole('button',{name:/开始分割视频/}).click();
 await page.locator('.status-card.success').waitFor({timeout:120000});
 const section=page.getByRole('region',{name:'分割结果'});
 const rows=section.locator('.result-item');
 if(await rows.count()!==50)throw Error('first page not bounded at 50');
 const nav=section.getByRole('navigation',{name:'分割结果分页'});
 await nav.getByRole('button',{name:'下一页'}).click();
 const remaining=await rows.count();
 if(remaining<1||remaining>50)throw Error('second page count wrong');
 const name=await rows.first().locator('.result-file-name strong').innerText();
 await section.getByRole('searchbox',{name:'搜索分割结果'}).fill(name);
 if(await rows.count()!==1)throw Error('search did not reset pagination');
 await section.getByRole('searchbox',{name:'搜索分割结果'}).fill('not-a-match');
 await section.getByText('没有匹配的片段').waitFor();
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:/导出处理报告 JSON/}).click()]);
 const report=JSON.parse(await readFile(await download.path(),'utf8'));
 if(report.outputs.length!==50+remaining||report.outputs.some(x=>!x.verification?.passed))throw Error('full report missing verified outputs');
 await mkdir('visual-regression',{recursive:true});
 await section.getByRole('searchbox',{name:'搜索分割结果'}).fill('');
 await section.scrollIntoViewIfNeeded();
 await themeOption(page,'light');await page.screenshot({path:'visual-regression/many-segments-light.png',animations:'disabled'});
 await themeOption(page,'dark');await page.screenshot({path:'visual-regression/many-segments-dark.png',animations:'disabled'});
 await page.setViewportSize({width:390,height:844});
 await section.getByRole('searchbox',{name:'搜索分割结果'}).fill('');
 await section.scrollIntoViewIfNeeded();
 if(await section.evaluate(el=>el.scrollWidth>el.clientWidth+1))throw Error('mobile result overflow');
 await page.screenshot({path:'visual-regression/many-segments-dark-390.png',animations:'disabled'});
 await input.setInputFiles({name:'invalid.mp4',mimeType:'video/mp4',buffer:Buffer.from('not a media file')});
 await page.getByRole('status',{name:'媒体读取失败'}).waitFor();
 if(await page.locator('.file-state .small-spinner').count())throw Error('failed read retained loading spinner');
 await input.setInputFiles({name:'valid-again.mp4',mimeType:'video/mp4',buffer:bytes});
 await page.getByRole('status',{name:'媒体已就绪'}).waitFor();
 console.log(JSON.stringify({invalidMediaRecovery:'passed',staleWorker:'passed',revokedOldPreview:'passed',newPreview:'passed',realSegments:report.outputs.length,search:'passed',completeManifest:'passed',mobileResults:'passed'}));
}finally{await browser.close()}
